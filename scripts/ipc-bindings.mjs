#!/usr/bin/env node
// S5-011: generate the typed TypeScript IPC surface from the Rust command signatures.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { registeredCommands, readRustSource } from "./lib/ui-invariants.mjs";

const OUTPUT = "src/ipc/bindings.ts";
const rustTypeToTs = new Map([
  ["String", "string"],
  ["i32", "number"],
  ["i64", "number"],
  ["usize", "number"],
  ["bool", "boolean"],
  ["()", "void"],
  ["Text", "string"],
  ["Name", "string"],
  ["LongText", "string"],
  ["Keyword", "string"],
  ["Token", "string"],
  ["VideoId", "string"],
  ["YtId", "string"],
  ["LibraryId", "string"],
  ["SpotifyId", "string"],
  ["SpotifyUri", "string"],
  ["Opt", "unknown"],
  ["Option", "unknown"],
  ["Vec", "unknown"],
]);

function splitTopLevel(value) {
  const parts = [];
  let start = 0;
  let depth = 0;
  for (let index = 0; index < value.length; index += 1) {
    if ("<([{".includes(value[index])) depth += 1;
    if (">)]}".includes(value[index])) depth -= 1;
    if (value[index] === "," && depth === 0) {
      parts.push(value.slice(start, index).trim());
      start = index + 1;
    }
  }
  if (value.slice(start).trim()) parts.push(value.slice(start).trim());
  return parts;
}

function matchingParen(source, open) {
  let depth = 0;
  for (let index = open; index < source.length; index += 1) {
    if (source[index] === "(") depth += 1;
    if (source[index] === ")" && --depth === 0) return index;
  }
  throw new Error(`unclosed argument list at ${open}`);
}

function typeToTs(type) {
  const normalized = type.replace(/\s+/g, " ").trim();
  const option = normalized.match(/^(?:Option|Opt)<(.+)>$/);
  if (option) return `${typeToTs(option[1])} | null`;
  const vector = normalized.match(/^Vec<(.+)>$/);
  if (vector) return `${typeToTs(vector[1])}[]`;
  if (rustTypeToTs.has(normalized)) return rustTypeToTs.get(normalized);
  if (/^[A-Z]\w*$/.test(normalized)) return normalized;
  throw new Error(`unsupported Rust IPC type: ${normalized}`);
}

function camelCase(name) {
  return name.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function commandSignatures(commands) {
  const source = readRustSource();
  const signatures = new Map();
  for (const match of source.matchAll(/#\[tauri::command\][\s\S]*?\bfn\s+(\w+)\s*\(/g)) {
    const name = match[1];
    if (!commands.has(name)) continue;
    const open = match.index + match[0].lastIndexOf("(");
    const close = matchingParen(source, open);
    const after = source.slice(close + 1).match(/^\s*->\s*([^\\{]+)\{/);
    if (!after) continue;
    const args = {};
    for (const argument of splitTopLevel(source.slice(open + 1, close))) {
      const separator = argument.indexOf(":");
      if (separator < 0) continue;
      const argName = argument.slice(0, separator).trim();
      const argType = argument.slice(separator + 1).trim();
      if (/^(tauri::State|tauri::AppHandle|AppHandle)/.test(argType)) continue;
      args[argName] = {
        type: typeToTs(argType),
        optional: /^(Opt|Option)</.test(argType),
      };
    }
    const result = after[1].trim().replace(/^crate::IpcResult</, "IpcResult<");
    const wrapped = result.match(/^IpcResult<(.+)>$/);
    if (!wrapped) throw new Error(`${name} does not return IpcResult`);
    signatures.set(name, { args, result: typeToTs(wrapped[1]) });
  }
  return signatures;
}

function render() {
  const commands = registeredCommands(readFileSync("src-tauri/src/lib.rs", "utf8"));
  const signatures = commandSignatures(new Set(commands));
  const missing = commands.filter((command) => !signatures.has(command));
  if (missing.length) throw new Error(`no Rust signature found for: ${missing.join(", ")}`);
  const lines = [
    "// Generated by `npm run check:ipc-bindings` from registered Rust commands. Do not edit by hand.",
    'import { invoke } from "@tauri-apps/api/core";',
    'import type {',
    "  DetailPage, DownloadInfo, HomePage, LibraryItemState, LibraryPlaylistItem, LocalItem,",
    "  LyricsPayload, PlayerCacheUsage, PlayerPayload, PlaylistContinuationPage, PlaylistPage,",
    "  QueuePage, RemoteHistoryPage, SearchPage, SessionStatus, SettingEntry, StatsPayload,",
    "  SpotifyLibraryNode, SpotifyLikedTracks, SpotifyPlaylistItem, SpotifyProfile,",
    "  SpotifySessionStatus, SpotifyTrackMatch, SpotifyTrackPage, UpdateSummary, YtItem, YouTubeSyncResult,",
    "} from \"../types\";",
    "",
    "type RustModels = {",
    "  DetailPage: DetailPage; DownloadInfo: DownloadInfo; HomePage: HomePage;",
    "  LibraryItemState: LibraryItemState; LibraryPlaylistItem: LibraryPlaylistItem; LocalItem: LocalItem;",
    "  LyricsPayload: LyricsPayload; PlayerCacheUsage: PlayerCacheUsage; PlayerPayload: PlayerPayload;",
    "  PlaylistContinuationPage: PlaylistContinuationPage; PlaylistPage: PlaylistPage; QueuePage: QueuePage;",
    "  RemoteHistoryPage: RemoteHistoryPage; SearchPage: SearchPage; SessionStatus: SessionStatus;",
    "  SettingEntry: SettingEntry; StatsPayload: StatsPayload; SpotifyLibraryNode: SpotifyLibraryNode;",
    "  SpotifyLikedTracks: SpotifyLikedTracks; SpotifyPlaylistItem: SpotifyPlaylistItem;",
    "  SpotifyProfile: SpotifyProfile; SpotifySessionStatus: SpotifySessionStatus;",
    "  SpotifyTrackMatch: SpotifyTrackMatch; SpotifyTrackPage: SpotifyTrackPage; UpdateSummary: UpdateSummary;",
    "  YtItem: YtItem; YouTubeSyncResult: YouTubeSyncResult;",
    "};",
    "type ResolveModel<T> = T extends keyof RustModels ? RustModels[T] : T;",
    "",
    "export type IpcCommandMap = {",
  ];
  for (const command of commands) {
    const signature = signatures.get(command);
    const fields = Object.entries(signature.args).map(([name, value]) => `${camelCase(name)}${value.optional ? "?" : ""}: ${value.type}`);
    lines.push(`  ${command}: { args: { ${fields.join("; ")} }; result: ResolveModel<${signature.result}> };`);
  }
  lines.push(
    "};",
    "",
    "export type IpcCommand = keyof IpcCommandMap;",
    "export type IpcArgs<C extends IpcCommand> = IpcCommandMap[C][\"args\"];",
    "export type IpcResult<C extends IpcCommand> = IpcCommandMap[C][\"result\"];",
    "export function invokeIpc<C extends IpcCommand>(command: C, args: IpcArgs<C>): Promise<IpcResult<C>> {",
    "  return invoke<IpcResult<C>>(command, args);",
    "}",
    "",
  );
  return lines.join("\n");
}

const output = render();
if (process.argv.includes("--check")) {
  if (readFileSync(OUTPUT, "utf8") !== output) {
    console.error(`${OUTPUT} is out of date; run npm run check:ipc-bindings`);
    process.exit(1);
  }
} else {
  mkdirSync("src/ipc", { recursive: true });
  writeFileSync(OUTPUT, output);
}
